"""Write comparison.md and comparison.json from a benchmark run.

    python -I report.py DATA_DIR > comparison.md

DATA_DIR is what the steps of README.md leave: manifest.tsv, results/
(run_all_html.sh, and the go-fast-html variants), scores.json
(score_text.py) and run.log.
"""
import json, os, platform, statistics, subprocess, sys
from importlib import metadata

D = sys.argv[1]
R = os.path.join(D, "results")
LABEL = {"go-fast-html": "**go-fast-html**", "selectolax": "selectolax (lexbor, C)", "resiliparse": "resiliparse (lexbor, C++)",
         "bs4-lxml": "BeautifulSoup + lxml", "inscriptis": "inscriptis", "html2text": "html2text (Python)",
         "markitdown": "markitdown", "trafilatura": "trafilatura (main content only)", "rs-html2text": "html2text (Rust crate)",
         "rs-htmd": "htmd (Rust crate)"}


def runs(workers):
    rows = []
    for t in LABEL:
        d = os.path.join(R, f"{t}-{workers}")
        if not os.path.exists(d):
            continue
        m = json.load(open(os.path.join(d, "measure.json")))
        res = [json.loads(l) for l in open(os.path.join(d, "results.jsonl"))]
        ts = sorted(x["s"] for x in res if not x["err"])
        q = lambda p: ts[int(p * (len(ts) - 1))] * 1000
        rows.append({"tool": t, "wall_s": m["wall_s"], "cpu_s": m["cpu_s"], "peak_mb": m["peak_rss_mb"], "files": len(res),
                     "failed": sum(1 for x in res if x["err"]), "p50_ms": q(.5), "p95_ms": q(.95), "p99_ms": q(.99),
                     "max_ms": ts[-1] * 1000})
    return sorted(rows, key=lambda r: r["wall_s"])


def versions():
    v = {}
    for p in ["beautifulsoup4", "lxml", "html2text", "inscriptis", "resiliparse", "selectolax", "markitdown", "trafilatura"]:
        try:
            v[p] = metadata.version(p)
        except metadata.PackageNotFoundError:
            pass
    lock = os.path.join(os.path.dirname(__file__), "rshtml", "Cargo.lock")
    if os.path.exists(lock):
        name = None
        for l in open(lock):
            if l.startswith("name = "):
                name = l.split('"')[1]
            elif l.startswith("version = ") and name in ("html2text", "htmd"):
                v[name + " (crate)"] = l.split('"')[1]
    return v


pages = sum(1 for _ in open(os.path.join(D, "manifest.tsv"))) - 1
size = sum(int(l.split("\t")[1]) for l in list(open(os.path.join(D, "manifest.tsv")))[1:])
one, many = runs(1), runs(24)
scores = json.load(open(os.path.join(D, "scores.json")))
cpu = next((l.split(":", 1)[1].strip() for l in open("/proc/cpuinfo") if l.startswith("model name")), platform.processor())
gov = subprocess.run(["go", "version"], capture_output=True, text=True).stdout.strip()
json.dump({"pages": pages, "bytes": size, "one_worker": one, "24_workers": many, "scores": scores, "versions": versions()},
          open(os.path.join(os.path.dirname(__file__), "comparison.json"), "w"), indent=1)

fast = {r["tool"]: r["wall_s"] for r in one}
gf = fast["go-fast-html"]
print("# go-fast-html against the tools in use today\n")
print("Generated by `bench/report.py`; do not edit. Numbers are from one machine and compare tools on that machine only.\n")
print(f"Machine: {cpu}, {os.cpu_count()} logical cores, {platform.platform()}, Python {platform.python_version()}, {gov}. "
      "Other sessions used the machine during the runs (the load average at each run is in `run.log`).\n")
print("Versions: " + ", ".join(f"{k} {v}" for k, v in versions().items()) + ".\n")
print(f"**Input:** {pages:,} HTML pages, {size / 2**30:.2f} GiB, the `text/html` 200 responses of the first 400 MB of one "
      "Common Crawl WARC file (CC-MAIN-2026-43), as served. Each tool reads every page in one long-lived process, "
      "the way a pipeline does, with one worker and with 24; the time of a page is the call alone, after its bytes are read. "
      "Wall time, CPU time and peak memory are of the whole process tree.\n")
for title, rows in (("One worker", one), ("24 workers", many)):
    print(f"## {title}\n")
    print("| Tool | Wall | Against go-fast-html | CPU | Peak memory | Failed | Median | 95th | 99th | Slowest page |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    base = next(r["wall_s"] for r in rows if r["tool"] == "go-fast-html")
    for r in rows:
        rel = "" if r["tool"] == "go-fast-html" else f"{r['wall_s'] / base:.2f} times"
        print(f"| {LABEL[r['tool']]} | {r['wall_s']:.2f} s | {rel} | {r['cpu_s']:.1f} s | {r['peak_mb']:,.0f} MB | {r['failed']} | "
              f"{r['p50_ms']:.2f} ms | {r['p95_ms']:.2f} ms | {r['p99_ms']:.2f} ms | {r['max_ms']:.0f} ms |")
    print()
print("## Accuracy\n")
print(f"Against the text Chromium shows for {scores['pages']} pages chosen at random (`reference_html.py`: JavaScript off, "
      "the network blocked, `document.body.innerText`; pages with fewer than 20 words left out), by words "
      "(`score_text.py`: precision is the share of a tool's words the browser shows, recall the share of the browser's words "
      "the tool gives, averaged over pages).\n")
print("| Tool | F1 | Precision | Recall |")
print("|---|---|---|---|")
lab = dict(LABEL, **{"go-fast-html-visible": "**go-fast-html**, what a browser shows (see README.md)",
                     "go-fast-html-nohidden": "go-fast-html, `Text()` without declared-hidden blocks",
                     "go-fast-html": "go-fast-html, `Text()`: everything"})
for k, v in sorted(scores["tools"].items(), key=lambda kv: -kv[1]["f1"]):
    name = k.rsplit("-", 1)[0] if k.endswith("-1") else k
    print(f"| {lab.get(name, name)} | {v['f1']:.3f} | {v['precision']:.3f} | {v['recall']:.3f} |")
print()
